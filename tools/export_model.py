"""Writes Java_web/js/model-data.js: everything the JavaScript site needs that is DATA, not code.

    source ~/venvs/iwsp/bin/activate
    python Java_web/tools/export_model.py

Developer tool. The website itself contains no Python and does not need this to run.
Re-run after features.py, segment.py or web/readout.json change (and re-port any changed
code in js/ by hand, then run tools/verify_parity.py).

Exported:
  * the logistic readout and ACR rules (web/readout.json), descriptor titles, feature docs
  * numeric tables taken from numpy/scipy so the JavaScript uses the very same constants:
    the polar sampling grid of segment.py and the Gaussian kernels scipy.ndimage builds
  * the bundled sample image and the desktop pipeline's result for it (the page self-test)
"""
import base64
import datetime
import hashlib
import json
import math
import sys
from pathlib import Path

import numpy as np
from scipy.ndimage import _filters

HERE = Path(__file__).resolve().parent.parent
ROOT = HERE.parent
sys.path.insert(0, str(ROOT / "web"))
sys.path.insert(0, str(ROOT))
import pipeline  # noqa: E402

SEG, FEAT, R = pipeline.SEG, pipeline.FEAT, pipeline.R
SIGMAS = (1.0, 1.5, 2.0, 3.0, 3.5, 6.0)          # every sigma features.py / pipeline.py passes to scipy
TOLERANCE = {"rel": 1e-5, "abs": 1e-8}           # page self-test: |js - desktop| <= rel * (|desktop| + abs/rel)


def clean(o):
    if isinstance(o, dict):
        return {k: clean(v) for k, v in o.items()}
    if isinstance(o, (list, tuple)):
        return [clean(v) for v in o]
    if isinstance(o, (float, np.floating)):
        return float(o) if math.isfinite(o) else None
    if isinstance(o, np.integer):
        return int(o)
    return o


def main():
    f32 = np.float32
    ang32 = np.linspace(0, 2 * np.pi, SEG.N_ANGLE, endpoint=False, dtype=f32)
    ang64 = np.linspace(0, 2 * np.pi, SEG.N_ANGLE, endpoint=False)
    kernels = {}
    for s in SIGMAS:
        lw = int(4.0 * s + 0.5)
        kernels[repr(s)] = {str(o): [float(v) for v in _filters._gaussian_kernel1d(s, o, lw)[::-1]] for o in (0, 2)}

    sample_png = (HERE / "assets" / "sample.png").read_bytes()
    meta = json.loads((HERE / "assets" / "sample.json").read_text())
    ref = pipeline.analyse(sample_png, meta["box"])

    model = {
        "built": datetime.date.today().isoformat(),
        "source_md5": {n: hashlib.md5((ROOT / n).read_bytes()).hexdigest()
                       for n in ("segment.py", "features.py", "web/pipeline.py", "web/readout.json")},
        "readout": R,
        "category_title": pipeline.CATEGORY_TITLE, "label_title": pipeline.LABEL_TITLE,
        "feature_docs": dict(FEAT.FEATURE_DOCS), "method": SEG.METHOD, "max_side": pipeline.MAX_SIDE,
        "seg": {
            "WIDTH_FRAC": SEG.WIDTH_FRAC, "HEIGHT_FRAC": SEG.HEIGHT_FRAC, "N_ANGLE": SEG.N_ANGLE, "N_RAD": SEG.N_RAD,
            "RAD_MIN": SEG.RAD_MIN, "RAD_MAX": SEG.RAD_MAX, "PRIOR_WEIGHT": SEG.PRIOR_WEIGHT,
            "EDGE_PCTILE": SEG.EDGE_PCTILE, "EDGE_CLIP": SEG.EDGE_CLIP, "MAX_STEP": SEG.MAX_STEP,
            "rad32": [float(v) for v in np.linspace(SEG.RAD_MIN, SEG.RAD_MAX, SEG.N_RAD, dtype=f32)],
            "cos32": [float(v) for v in np.cos(ang32)], "sin32": [float(v) for v in np.sin(ang32)],
            "cos64": [float(v) for v in np.cos(ang64)], "sin64": [float(v) for v in np.sin(ang64)],
        },
        "gauss_kernels": kernels,
        "sample": {"name": meta["name"], "box": meta["box"], "note": meta.get("note", ""),
                   "data_url": "data:image/png;base64," + base64.b64encode(sample_png).decode()},
        "golden": {"features": clean(ref["features"]), "tr": ref["tr"], "total_points": ref["total_points"],
                   "chosen": {g: c["chosen"] for g, c in ref["categories"].items()}},
        "tolerance": TOLERANCE,
    }
    out = HERE / "js" / "model-data.js"
    out.write_text("// GENERATED by tools/export_model.py -- do not edit by hand.\n"
                   "window.IWSP = window.IWSP || {};\nIWSP.MODEL = " + json.dumps(clean(model)) + ";\n")
    print(f"wrote {out.relative_to(ROOT)} ({out.stat().st_size / 1024:.0f} kB): {len(R['features'])} features, "
          f"{len(R['labels'])} labels, sample TR{ref['tr']}")


if __name__ == "__main__":
    main()
